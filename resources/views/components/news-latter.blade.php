document.addEventListener('DOMContentLoaded', function() {
    const form = document.getElementById('newsletter-form');
    const submitBtn = document.getElementById('subscribe-btn');
    const successModal = document.getElementById('success-modal');

    form.addEventListener('submit', function(e) {
        e.preventDefault();
        
        // Basic email validation
        const emailInput = form.querySelector('[name="email"]');
        const email = emailInput.value.trim();
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

        if (!email || !emailRegex.test(email)) {
            // Show error state
            emailInput.classList.add('border-red-500', 'bg-red-50');
            emailInput.classList.remove('border-gray-200');
            
            // Shake animation
            emailInput.classList.add('animate-bounce');
            setTimeout(() => {
                emailInput.classList.remove('animate-bounce');
            }, 1000);
            
            return;
        }

        // Remove error state
        emailInput.classList.remove('border-red-500', 'bg-red-50');
        emailInput.classList.add('border-gray-200');

        // Show loading state
        const btnText = submitBtn.querySelector('span');
        const btnSpinner = submitBtn.querySelector('.animate-spin').parentElement;
        
        btnText.textContent = 'Subscribing...';
        btnSpinner.classList.remove('hidden');
        submitBtn.disabled = true;
        submitBtn.classList.add('opacity-75', 'cursor-not-allowed');

        // Simulate subscription (replace with actual form submission)
        setTimeout(() => {
            successModal.classList.remove('hidden');
            
            // Reset form
            form.reset();
            
            // Reset button
            btnText.textContent = 'Subscribe Now';
            btnSpinner.classList.add('hidden');
            submitBtn.disabled = false;
            submitBtn.classList.remove('opacity-75', 'cursor-not-allowed');
        }, 2000);

        // Uncomment for actual form submission
        // this.submit();
    });

    // Remove error state on input
    const emailInput = form.querySelector('[name="email"]');
    emailInput.addEventListener('input', function() {
        if (this.classList.contains('border-red-500')) {
            this.classList.remove('border-red-500', 'bg-red-50');
            this.classList.add('border-gray-200');
        }
    });
});
</script>